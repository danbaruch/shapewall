// Writes src/og-versions.js: a short content hash for each share card in public/og. The pages link a card as
// /og/<name>.jpg?v=<hash>, so a changed card is a new URL and no cache (the CDN's day, a social network's much longer one)
// keeps showing the old image. og.mjs and social.mjs run this after they write the cards; test/build.test.js checks the
// hashes match the files. Run on its own after replacing a card by hand: node scripts/og-versions.mjs
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const SITE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const OG_DIR = path.join(SITE, 'public', 'og')
const OUT = path.join(SITE, 'src', 'og-versions.js')

export const ogHash = (file) => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex').slice(0, 10)

export function ogVersions() {
  const names = fs
    .readdirSync(OG_DIR)
    .filter((name) => name.endsWith('.jpg'))
    .sort()
  return Object.fromEntries(names.map((name) => [name.slice(0, -4), ogHash(path.join(OG_DIR, name))]))
}

export function writeOgVersions() {
  const lines = Object.entries(ogVersions()).map(([name, hash]) => `  ${/^[a-z_$][\w$]*$/i.test(name) ? name : `'${name}'`}: '${hash}',`)
  fs.writeFileSync(
    OUT,
    `// Generated by scripts/og-versions.mjs from public/og: a content hash per share card, for cache-busting its URL.\nexport const OG_VERSIONS = {\n${lines.join('\n')}\n}\n`,
  )
  return OUT
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(`og: ${path.relative(SITE, writeOgVersions())}`)
}
